export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(
    () => {
      const savedLanguage = localStorage.getItem("agrosmart_language");
      return SUPPORTED_LANGUAGES.some(({ value }) => value === savedLanguage)
        ? savedLanguage
        : "en";
    }
  );

  useEffect(() => {
    localStorage.setItem("agrosmart_language", language);
    document.documentElement.lang = language;
  }, [language]);

  const t = (text) => {
    if (language !== "kn" || typeof text !== "string") return text;
    return translations[text] || translations[text.toLowerCase()] || stateLocationTranslations[text] || locationTranslations[text] || text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}
